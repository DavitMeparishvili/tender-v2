-- Preserve and connect existing tender locations where a catalog spelling
-- matches. The population order resolves the two duplicated settlement names
-- deterministically to the larger place.
UPDATE "Tender" AS tender
SET "georgianPlaceId" = (
  SELECT place."id"
  FROM "GeorgianPlace" AS place
  WHERE lower(place."nameEn") = lower(tender."city")
     OR place."nameKa" = tender."city"
  ORDER BY place."population" DESC, place."id"
  LIMIT 1
)
WHERE tender."city" IS NOT NULL;

